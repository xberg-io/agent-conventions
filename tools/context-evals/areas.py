#!/usr/bin/env python3
"""Render one repository's ai-rulez `[exposure]` area map (the `areas_file` format) from domains.toml.

domains.toml stays the single taxonomy. Each domain becomes an area with its owner and terms; a domain the repository
owns is `shared`, so naming it at session start is not leakage, and every other domain's terms leak. Domain `paths`
are polyrepo-relative directories, which name no directory inside a repository, so the map carries no path claims.

An area's `exclude` lists the compounds of domains.toml that contain one of its terms without naming it: the top-level
`names` and the other domains' terms (`xberg-io` and `xberg-enterprise` for the term `xberg`). The `[[accept]]` entries
that apply to the repository and the harness become the map's `[[accept]]`, since ai-rulez fails on an entry that
accepts nothing.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

DOMAINS = Path(__file__).resolve().parent / "domains.toml"
HEADER = "# Generated by tools/context-evals/areas.py from domains.toml. Do not edit: change domains.toml and rerun.\n"
HARNESSES = ("claude", "codex")
SKILL_DIRS = {"claude": ".claude/skills", "codex": ".agents/skills"}
AGENT_PATHS = {"claude": ".claude/agents/{}.md", "codex": ".codex/agents/{}.toml"}


def contains_term(compound: str, term: str) -> bool:
    """`term` bounded by non-word characters inside `compound`: `xberg` in `xberg-io`, not in `xberger`."""
    return re.search(rf"(?<!\w){re.escape(term)}(?!\w)", compound, re.IGNORECASE) is not None


def compounds(domains: dict) -> list[str]:
    """Every name in its own right: the top-level `names`, then each domain's terms, without repeats."""
    seen: dict[str, None] = {name.lower(): None for name in domains.get("names", [])}
    for domain in domains.get("domain", {}).values():
        seen.update((term.lower(), None) for term in domain.get("terms", []))
    return list(seen)


def exclusions(terms: list[str], names: list[str]) -> list[str]:
    """The names that contain, and are longer than, one of `terms`."""
    lowered = {term.lower() for term in terms}
    return [name for name in names if name not in lowered and any(contains_term(name, term) for term in lowered)]


def accept_path(entry: dict, harness: str) -> str:
    """The project-relative path of an accepted artifact: `skill:NAME`, `agent:NAME`, a path, or every file."""
    artifact = entry.get("artifact")
    if artifact is None:
        return "**"
    # scoring.py matches `artifact` as a pattern; a literal is the subset both readers agree on.
    if re.search(r"[\\^$|()*+?{}\[\]]", artifact):
        raise ValueError(f"[[accept]] artifact {artifact!r} is a pattern; name a skill:, agent: or a path")
    kind, _, name = artifact.partition(":")
    if kind == "skill" and name:
        return f"{SKILL_DIRS[harness]}/{name}/SKILL.md"
    if kind == "agent" and name:
        return AGENT_PATHS[harness].format(name)
    return artifact


def accepts(domains: dict, repo: str, harness: str) -> list[dict]:
    """The acceptances that hold in `repo` under `harness`: `repo` is a full-match pattern, `harnesses` a list."""
    out = []
    for entry in domains.get("accept", []):
        if not re.fullmatch(entry.get("repo", ".*"), repo):
            continue
        if harness not in entry.get("harnesses", HARNESSES):
            continue
        if not entry.get("term") or not entry.get("reason"):
            raise ValueError(f"[[accept]] needs a term and a reason: {entry}")
        out.append(
            {"term": entry["term"], "path": accept_path(entry, harness), "reason": " ".join(entry["reason"].split())}
        )
    return out


def render(domains: dict, repo: str, harness: str = "claude") -> str:
    repos = domains.get("repos", {})
    if repo not in repos:
        raise ValueError(f"{repo!r} is not listed under [repos] in domains.toml")
    if harness not in HARNESSES:
        raise ValueError(f"harness must be one of {', '.join(HARNESSES)}, not {harness!r}")
    owned = set(repos[repo].get("domains", []))
    areas = domains.get("domain", {})
    unknown = owned - areas.keys()
    if unknown:
        raise ValueError(f"{repo!r} owns undefined domains: {', '.join(sorted(unknown))}")
    names = compounds(domains)
    blocks = []
    for name, domain in areas.items():
        terms = domain.get("terms", [])
        block = (
            f"[[area]]\nname = {json.dumps(name)}\nowner = {json.dumps(domain.get('owner', ''))}\n"
            f"terms = [{', '.join(json.dumps(term) for term in terms)}]\n"
        )
        excluded = exclusions(terms, names)
        if excluded:
            block += f"exclude = [{', '.join(json.dumps(item) for item in excluded)}]\n"
        blocks.append(block + f"shared = {'true' if name in owned else 'false'}\n")
    blocks.extend(
        "[[accept]]\n" + "".join(f"{key} = {json.dumps(value)}\n" for key, value in entry.items())
        for entry in accepts(domains, repo, harness)
    )
    return HEADER + "\n" + "\n".join(blocks)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", required=True, help="Name the repository is listed under in domains.toml")
    parser.add_argument("--harness", choices=HARNESSES, default="claude", help="Harness whose acceptances apply")
    parser.add_argument("--domains", type=Path, default=DOMAINS)
    parser.add_argument("--out", type=Path, help="Write the map here instead of standard output")
    args = parser.parse_args()
    try:
        rendered = render(tomllib.loads(args.domains.read_text()), args.repo, args.harness)
    except (OSError, ValueError, tomllib.TOMLDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.out is None:
        sys.stdout.write(rendered)
    else:
        args.out.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
